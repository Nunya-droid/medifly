/**
 * Generates src/components/ui/icons.ts with per-icon imports for every lucide icon used in src/.
 * Importing from the package root bundles all ~1,600 icons because Metro does not tree-shake;
 * per-icon imports keep the web bundle small. Run: node scripts/generate-icons.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = path.join(root, 'src');
const out = path.join(src, 'components', 'ui', 'icons.ts');
const indexFile = path.join(root, 'node_modules', 'lucide-react-native', 'dist', 'esm', 'lucide-react-native.mjs');

// Map every exported name (including aliases) to its icon module.
const index = fs.readFileSync(indexFile, 'utf8');
const nameToFile = {};
for (const m of index.matchAll(/export \{([^}]+)\} from '\.\/icons\/([a-z0-9-]+)\.mjs'/g)) {
  for (const part of m[1].split(',')) {
    const alias = part.trim().match(/default as (\w+)/);
    if (alias) nameToFile[alias[1]] = m[2];
  }
}

const used = new Set();
const walk = (dir) => {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (/\.(tsx?|jsx?)$/.test(f) && p !== out) {
      const text = fs.readFileSync(p, 'utf8');
      for (const m of text.matchAll(/import \{([^}]+)\} from '(?:lucide-react-native|@\/components\/ui\/icons)'/g)) {
        for (const raw of m[1].split(',').map((s) => s.trim()).filter(Boolean)) {
          if (raw.startsWith('type ')) continue;
          used.add(raw.split(/\s+as\s+/)[0]); // `User as UserIcon` → User
        }
      }
    }
  }
};
walk(src);

const missing = [...used].filter((n) => !nameToFile[n]);
if (missing.length) {
  console.error('Unknown lucide icons:', missing.join(', '));
  process.exit(1);
}
const lines = [...used].sort().map((n) => `export { default as ${n} } from 'lucide-react-native/icons/${nameToFile[n]}';`);
fs.writeFileSync(
  out,
  `/* Generated by scripts/generate-icons.js — per-icon imports keep the bundle small. */\nexport type { LucideIcon } from 'lucide-react-native';\n${lines.join('\n')}\n`
);
console.log(`Wrote ${used.size} icons to ${path.relative(root, out)}`);
